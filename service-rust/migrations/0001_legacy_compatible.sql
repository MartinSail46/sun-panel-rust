-- Keep the original GORM singular table names and columns for data migration.
CREATE TABLE IF NOT EXISTS user (
 id INTEGER PRIMARY KEY AUTOINCREMENT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, deleted_at TEXT,
 username TEXT NOT NULL DEFAULT '', password TEXT NOT NULL DEFAULT '', name TEXT NOT NULL DEFAULT '',
 head_image TEXT NOT NULL DEFAULT '', status INTEGER NOT NULL DEFAULT 1, role INTEGER NOT NULL DEFAULT 2,
 mail TEXT NOT NULL DEFAULT '', referral_code TEXT NOT NULL DEFAULT '', token TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS rust_user_username ON user(username);
CREATE TABLE IF NOT EXISTS item_icon_group (
 id INTEGER PRIMARY KEY AUTOINCREMENT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, deleted_at TEXT,
 icon TEXT NOT NULL DEFAULT '', title TEXT NOT NULL DEFAULT '', description TEXT NOT NULL DEFAULT '',
 sort INTEGER NOT NULL DEFAULT 0, user_id INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS rust_group_owner_sort ON item_icon_group(user_id, deleted_at, sort);
CREATE TABLE IF NOT EXISTS item_icon (
 id INTEGER PRIMARY KEY AUTOINCREMENT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, deleted_at TEXT,
 icon_json TEXT NOT NULL DEFAULT '{}', title TEXT NOT NULL DEFAULT '', url TEXT NOT NULL DEFAULT '',
 lan_url TEXT NOT NULL DEFAULT '', description TEXT NOT NULL DEFAULT '', open_method INTEGER NOT NULL DEFAULT 2,
 sort INTEGER NOT NULL DEFAULT 0, item_icon_group_id INTEGER NOT NULL, user_id INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS rust_icon_group_owner_sort ON item_icon(user_id, item_icon_group_id, deleted_at, sort);
CREATE TABLE IF NOT EXISTS user_config (user_id INTEGER NOT NULL, panel_json TEXT NOT NULL DEFAULT '{}', search_engine_json TEXT NOT NULL DEFAULT '{}');
CREATE TABLE IF NOT EXISTS module_config (
 id INTEGER PRIMARY KEY AUTOINCREMENT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, deleted_at TEXT,
 user_id INTEGER NOT NULL, name TEXT NOT NULL, value_json TEXT NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS system_setting (id INTEGER PRIMARY KEY AUTOINCREMENT, config_name TEXT NOT NULL, config_value TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS file (
 id INTEGER PRIMARY KEY AUTOINCREMENT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, deleted_at TEXT,
 src TEXT NOT NULL DEFAULT '', user_id INTEGER NOT NULL, file_name TEXT NOT NULL DEFAULT '',
 method INTEGER NOT NULL DEFAULT 0, ext TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS rust_file_owner ON file(user_id, deleted_at);
CREATE TABLE IF NOT EXISTS notice (
 id INTEGER PRIMARY KEY AUTOINCREMENT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, deleted_at TEXT,
 title TEXT NOT NULL DEFAULT '', content TEXT NOT NULL DEFAULT '', display_type INTEGER NOT NULL DEFAULT 0,
 one_read INTEGER NOT NULL DEFAULT 0, url TEXT NOT NULL DEFAULT '', is_login INTEGER NOT NULL DEFAULT 0, user_id INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE sessions (
 token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES user(id) ON DELETE CASCADE,
 expires_at INTEGER NOT NULL, created_at INTEGER NOT NULL DEFAULT (unixepoch())
);
CREATE INDEX rust_sessions_expiry ON sessions(expires_at);
CREATE INDEX rust_sessions_owner ON sessions(user_id);
